CREATE TABLE TBL_CONCERTS (
    CONCERT_ID     CHAR(4) PRIMARY KEY,
    VENUE_ID       CHAR(4)      NOT NULL,
    CONCERT_TITLE  VARCHAR2(15),
    ARTIST_NAME    VARCHAR2(10),
    CONCERT_DATE   DATE,
    START_TIME     DATE,
    END_TIME       DATE,
    BASE_PRICE     NUMBER(10),
    STATUS         NUMBER(1),
    CONSTRAINT FK_TBL_CONCERTS_VENUE FOREIGN KEY (VENUE_ID)
        REFERENCES TBL_VENUES (VENUE_ID)
);

